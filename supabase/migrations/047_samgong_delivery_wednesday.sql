-- ============================================================
-- 산방식당 — 삼공밥상 배송요일 고정: 주 1회 수요일
-- ============================================================
-- 배경:
--   삼공밥상(강원 횡성)은 서울·내륙 권역이지만 주 3회(월·수·금)가 아니라
--   주 1회 수요일 배송으로 운영한다.
--
--   delivery_days = [3]  → 수요일 출고·도착
--   마감은 서울·내륙 공통 규칙인 '출고 전일 17시' = 화요일 17시
--   (src/lib/delivery-schedule.ts 의 getSeoulSchedule)
--
-- 기존 주문 영향 없음:
--   ORD-20260826-0260 (ship_date 2026-08-28, 이미 출고완료)은
--   주문 생성 시점의 ship_date 가 각 행에 저장되어 있어 이 변경의 영향을 받지 않는다.
--   → 이 건은 예정대로 바로 배송하고, 다음 주문부터 수요일 스케줄 적용.
-- ============================================================

UPDATE public.stores
SET delivery_days = ARRAY[3]
WHERE id = '56f3964a-9411-42ac-a19f-63be624eb5f3';  -- 삼공밥상

